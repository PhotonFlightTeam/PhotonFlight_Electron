    ADD CONSTRAINT anomalies_pkey PRIMARY KEY (anomaly_id);

ALTER TABLE ONLY public.app_user
    ADD CONSTRAINT app_user_email_key UNIQUE (email);

ALTER TABLE ONLY public.app_user
    ADD CONSTRAINT app_user_pkey PRIMARY KEY (user_id);

ALTER TABLE ONLY public.drone
    ADD CONSTRAINT drone_pkey PRIMARY KEY (drone_id);

ALTER TABLE ONLY public.drone
    ADD CONSTRAINT drone_serial_number_key UNIQUE (serial_number);

ALTER TABLE ONLY public.lidar_data
    ADD CONSTRAINT lidar_data_pkey PRIMARY KEY (lidar_id);

ALTER TABLE ONLY public.maps
    ADD CONSTRAINT maps_pkey PRIMARY KEY (map_id);

ALTER TABLE ONLY public.picture
    ADD CONSTRAINT picture_pkey PRIMARY KEY (picture_id);

