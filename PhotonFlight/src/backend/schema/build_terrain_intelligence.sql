CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;

CREATE TABLE public.anomalies (
    anomaly_id bigint NOT NULL,
    lidar_id bigint,
    anomaly_type character varying(100) NOT NULL,
    description text,
    latitude double precision,
    longitude double precision,
    status character varying(50) DEFAULT 'suspected'::character varying,
    created_time timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    map_id bigint NOT NULL,
    verification_status character varying(20) DEFAULT 'pending'::character varying NOT NULL,
    verification_picture_id bigint,
    CONSTRAINT anomalies_verification_status_check CHECK (((verification_status)::text = ANY ((ARRAY['pending'::character varying, 'confirmed'::character varying, 'rejected'::character varying])::text[])))
);

CREATE SEQUENCE public.anomalies_anomaly_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE public.anomalies_anomaly_id_seq OWNED BY public.anomalies.anomaly_id;

CREATE TABLE public.app_user (
    user_id bigint NOT NULL,
    name character varying(150) NOT NULL,
    email character varying(255) NOT NULL,
    password_hash text CONSTRAINT app_user_password_has_not_null NOT NULL
);

CREATE SEQUENCE public.app_user_user_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE public.app_user_user_id_seq OWNED BY public.app_user.user_id;

CREATE TABLE public.drone (
    drone_id bigint NOT NULL,
    name character varying(150) NOT NULL,
    type character varying(100),
    serial_number character varying(150),
    status character varying(50),
    user_id bigint
);

CREATE SEQUENCE public.drone_drone_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE public.drone_drone_id_seq OWNED BY public.drone.drone_id;

CREATE TABLE public.lidar_data (
    lidar_id bigint NOT NULL,
    file_location text,
    file_format character varying(50),
    uploaded_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    uploaded_by bigint,
    latitude double precision,
    longitude double precision,
    map_id bigint NOT NULL
);

CREATE SEQUENCE public.lidar_data_lidar_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE public.lidar_data_lidar_id_seq OWNED BY public.lidar_data.lidar_id;

CREATE TABLE public.maps (
    map_id bigint NOT NULL,
    name character varying(150) NOT NULL,
    description text,
    created_by bigint,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    location_name character varying,
    latitude double precision,
    longitude double precision
);

ALTER TABLE public.maps ALTER COLUMN map_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.maps_map_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.picture (
    picture_id bigint NOT NULL,
    file_location text NOT NULL,
    capture_time timestamp without time zone,
    uploaded_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    uploaded_by bigint,
    width_px integer,
    height_px integer,
    map_id bigint NOT NULL
);

CREATE SEQUENCE public.picture_picture_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE public.picture_picture_id_seq OWNED BY public.picture.picture_id;

ALTER TABLE ONLY public.anomalies ALTER COLUMN anomaly_id SET DEFAULT nextval('public.anomalies_anomaly_id_seq'::regclass);

ALTER TABLE ONLY public.app_user ALTER COLUMN user_id SET DEFAULT nextval('public.app_user_user_id_seq'::regclass);

ALTER TABLE ONLY public.drone ALTER COLUMN drone_id SET DEFAULT nextval('public.drone_drone_id_seq'::regclass);

ALTER TABLE ONLY public.lidar_data ALTER COLUMN lidar_id SET DEFAULT nextval('public.lidar_data_lidar_id_seq'::regclass);

ALTER TABLE ONLY public.picture ALTER COLUMN picture_id SET DEFAULT nextval('public.picture_picture_id_seq'::regclass);

