    ADD CONSTRAINT lidar_data_map_id_fkey FOREIGN KEY (map_id) REFERENCES public.maps(map_id);

ALTER TABLE ONLY public.maps
    ADD CONSTRAINT maps_created_by_fkey FOREIGN KEY (created_by) REFERENCES public.app_user(user_id);

